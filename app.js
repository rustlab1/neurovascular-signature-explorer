  function parseRecord(buf, off, len) {
    var dv = new DataView(buf, off, len), p = 0, G = IDX.groups.length;
    var rec = { max: dv.getFloat32(0, true), means: new Array(G), pct: new Array(G), de: [], blocks: [] };
    p = 4;
    for (var g = 0; g < G; g++) { var v = dv.getUint16(p, true); rec.means[g] = v === 65535 ? null : v / 1000; p += 2; }
    for (g = 0; g < G; g++) { var u = dv.getUint8(p); rec.pct[g] = u === 255 ? null : u / 250; p += 1; }
    var nde = dv.getUint16(p, true); p += 2;
    for (var k = 0; k < nde; k++) {
      var c = dv.getUint8(p), p1 = dv.getUint8(p + 7), p2 = dv.getUint8(p + 8);
      rec.de.push({ ctx: c & 127, sig: c >= 128, fc: dv.getInt16(p + 1, true) / 1000, padj: dv.getFloat32(p + 3, true),
        p1: p1 === 255 ? null : p1 / 250, p2: p2 === 255 ? null : p2 / 250 });
      p += 9;
    }
    function varint() { var x = 0, sh = 0, b; do { b = dv.getUint8(p++); x += (b & 127) * Math.pow(2, sh); sh += 7; } while (b & 128); return x; }
    for (var bI = 0; bI < IDX.blocks.length; bI++) {
      var n = varint(), idx = new Int32Array(n), val = new Uint8Array(n), prev = -1;
      for (k = 0; k < n; k++) { prev += varint(); idx[k] = prev; }
      for (k = 0; k < n; k++) val[k] = dv.getUint8(p++);
      rec.blocks.push({ idx: idx, val: val });
    }
    return rec;
  }
  function loadGene(gi) {
    if (!recCache[gi]) {
      var so = geneOff[gi];
      recCache[gi] = fetchShard(so[0]).then(function (buf) { return parseRecord(buf, so[1], IDX.len[gi]); });
    }
    return recCache[gi];
  }
