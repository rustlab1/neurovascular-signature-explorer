        var sub = geneMode ? (nShown ? Math.round(100 * nExpr / nShown) : 0) + "% expressing" : fmtN(nShown) + " of " + fmtN(nTot) + " shown";
        var pc = panelCanvas(ds, cond, cond ? "Disease" : "Control", sub);
        grid.appendChild(pc.panel);
        var colorFn;
        if (geneMode) {
          var vv = vals[ds];
          colorFn = function (j) { return vv[j] === 0 ? "#e2e2e2" : rgb(rampColor(EXPR_RAMP, qmax ? vv[j] / qmax : 0)); };
        } else {
          colorFn = function (j) { return S.colors[U.lab[j]]; };
        }
        pc.draw = function () { drawPoints(pc.canvas, U, cond, colorFn, order); };
