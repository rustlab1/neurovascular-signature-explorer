  // autocomplete on an input
  function makeAC(input, box) {
    var items = [], sel = -1;
    function search(q) {
      q = q.toUpperCase(); var starts = [], incl = [], G = IDX.genes;
      for (var i = 0; i < G.length && starts.length < 12; i++) if (G[i].toUpperCase().indexOf(q) === 0) starts.push(G[i]);
      for (var j = 0; j < G.length && starts.length + incl.length < 12; j++) if (G[j].toUpperCase().indexOf(q) > 0) incl.push(G[j]);
      return starts.concat(incl);
    }
    function show() {
      var q = input.value.trim();
      if (!q || !IDX) { box.style.display = "none"; return; }
      items = search(q); sel = -1;
      if (!items.length) { box.style.display = "none"; return; }
      box.innerHTML = "";
      items.forEach(function (g) { var d = el("div", null, '<span class="g">' + esc(g) + '</span>'); d.onclick = function () { pick(g); }; box.appendChild(d); });
      box.style.display = "block";
    }
    function pick(g) { box.style.display = "none"; selectGene(g); }
    input.addEventListener("input", show);
    input.addEventListener("keydown", function (e) {
      var ch = box.children;
      if (e.key === "ArrowDown") { sel = Math.min(sel + 1, ch.length - 1); e.preventDefault(); }
      else if (e.key === "ArrowUp") { sel = Math.max(sel - 1, 0); e.preventDefault(); }
      else if (e.key === "Enter") {
        e.preventDefault();
        var exact = IDX && resolveGene(input.value) >= 0;
        if (sel >= 0 && items[sel] && box.style.display === "block") pick(items[sel]);
        else if (exact || !items.length || box.style.display !== "block") pick(input.value.trim());
        else pick(items[0]);
        return;
      } else return;
      for (var k = 0; k < ch.length; k++) ch[k].className = (k === sel ? "sel" : "");
    });
    document.addEventListener("click", function (e) { if (!box.contains(e.target) && e.target !== input) box.style.display = "none"; });
  }

