  function pctOf(rec, ds, set, label, cond) { var i = groupIdx[ds + "|" + set + "|" + label + "|" + cond]; return i == null ? null : rec.pct[i]; }
  function inDataset(rec, ds) {
    for (var i = 0; i < IDX.groups.length; i++) if (IDX.groups[i].ds === ds && rec.means[i] != null) return true;
    return false;
  }

